export function carMatchesFilter(car, f, engineById) {
  if (f === 'all') return true;
  if (f === 'classic' || f === 'import') return car.era === f;
  if (f === 'korean') return car.brand === 'Hyundai' || car.brand === 'KIA';
  if (f === 'chinese') return ['Changan', 'MG', 'Haval', 'Proton', 'Peugeot', 'BAIC', 'BYD'].includes(car.brand);
  if (f === 'ev') { const e = engineById[car.engine]; return !!e && (e.fuel === 'electric' || e.fuel === 'hybrid'); }
  return car.brand === f;
}

